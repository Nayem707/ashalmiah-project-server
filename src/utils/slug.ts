import slugify from 'slugify';

/**
 * URL slug that keeps non-Latin scripts (e.g. Bengali) instead of stripping them,
 * which `slugify(..., { strict: true })` does and leaves an empty base.
 */
export function toSlug(text: string, fallback: string): string {
  const latin = slugify(text, { lower: true, strict: true });
  const hasNonLatin = /[^\p{Script=Latin}\p{N}\s\p{P}\p{S}]/u.test(text);

  const slug = hasNonLatin
    ? text
        .normalize('NFC')
        .toLowerCase()
        .replace(/[^\p{L}\p{M}\p{N}]+/gu, '-')
        .replace(/^-+|-+$/g, '')
    : latin;

  return slug || fallback;
}

/** Slugs generated by the old strict slugify for non-Latin names: "", "-1", "-2", ... */
export function isBrokenSlug(slug: string | null | undefined): boolean {
  return !slug || /^-/.test(slug) || !/[\p{L}\p{N}]/u.test(slug);
}
